package main

import (
	"bytes"
	"errors"
	"fmt"
	"go/format"
	"io"
	"text/template"
)

// kubeAPIAuthImageKey is the build.yaml key holding the kube-api-auth image.
const kubeAPIAuthImageKey = "defaultKubeApiAuthImage"

// toolsSystemImagesTmpl renders pkg/apis/management.cattle.io/v3/tools_system_images.go.
// The v3 package cannot import pkg/buildconfig (that would pull in all of Rancher
// through a separate module), so the value is written out as a literal instead.
const toolsSystemImagesTmpl = `// Code generated by pkg/codegen/buildconfig/main.go. DO NOT EDIT.

package v3

var (
	ToolsSystemImages = struct {
		AuthSystemImages AuthSystemImages
	}{
		AuthSystemImages: AuthSystemImages{
			KubeAPIAuth: {{ printf "%q" .KubeAPIAuth }},
		},
	}
)
`

// ToolsSystemImagesWriter generates the v3 ToolsSystemImages variable from
// the values in build.yaml.
type ToolsSystemImagesWriter struct {
	Config map[string]string // build.yaml parsed config
	Output io.Writer         // generated tools_system_images.go
}

// Run renders the Go source for ToolsSystemImages and writes it to Output.
// Nothing is written to Output if rendering or formatting fails.
func (w *ToolsSystemImagesWriter) Run() error {
	if w.Config == nil {
		return errors.New("nil config")
	}
	if w.Output == nil {
		return errors.New("nil output")
	}

	image := w.Config[kubeAPIAuthImageKey]
	if image == "" {
		return fmt.Errorf("%q is missing or empty in build config", kubeAPIAuthImageKey)
	}

	tmpl, err := template.New("").Parse(toolsSystemImagesTmpl)
	if err != nil {
		return err
	}
	buf := new(bytes.Buffer)
	if err := tmpl.Execute(buf, struct{ KubeAPIAuth string }{KubeAPIAuth: image}); err != nil {
		return err
	}

	formatted, err := format.Source(buf.Bytes())
	if err != nil {
		return err
	}
	_, err = w.Output.Write(formatted)
	return err
}
